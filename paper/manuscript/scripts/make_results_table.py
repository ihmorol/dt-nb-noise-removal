"""Build the manuscript's results tables from results/EXP-E9_farid/.

    .venv/bin/python scripts/make_results_table.py     (from paper/manuscript/)

Writes into tables/:
    table_results.tex            Table II: protocol-B means over the datasets
    table_results_datasets.tex   per-dataset accuracy, all ten arms
    table_results_A.tex          protocol A (before-CV) vs B for the cleaning arms
No number is hand-typed in main.tex; rerun this after every new e9_farid run.
"""
import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parents[1]
RESULTS = HERE.parents[1] / "results" / "EXP-E9_farid"
TABLES = HERE / "tables"

# manuscript row order; LABEL maps an arm to the manuscript's name for it
ROWS = ["baseline->NB", "baseline->DT", "Alg1->DT", "Alg2->NB",
        "C1 N->A->NB", "C1 N->A->DT", "C2 A->N->NB", "C2 A->N->DT"]
LABEL = {"baseline->NB": "NB", "baseline->DT": "C4.5",
         "Alg1->DT": "Algorithm 1", "Alg2->NB": "Algorithm 2",
         "Alg1->NB": "Alg.\\ 1, NB final", "Alg2->DT": "Alg.\\ 2, DT final",
         "C1 N->A->NB": "Instances first, NB", "C1 N->A->DT": "Instances first, DT",
         "C2 A->N->NB": "Attributes first, NB", "C2 A->N->DT": "Attributes first, DT"}
ALL_ARMS = ROWS[:4] + ["Alg1->NB", "Alg2->DT"] + ROWS[4:]


def write(name, text):
    TABLES.mkdir(exist_ok=True)
    (TABLES / name).write_text(text, encoding="utf-8")
    print(f"[saved] tables/{name}")


def main():
    metrics = pd.read_csv(RESULTS / "metrics.csv")
    per_fold = pd.read_csv(RESULTS / "per_fold.csv")
    config = json.loads((RESULTS / "config.json").read_text())
    seeds = config["seeds"]
    header = (f"% generated by scripts/make_results_table.py; do not edit\n"
              f"% {metrics.dataset.nunique()} datasets, seeds {seeds[0]}..{seeds[-1]},\n"
              f"% {config['j48']}, {config['nb']}\n")

    b = metrics[metrics.protocol == "B refit-per-fold"]
    # Table II: dataset means already sit in metrics.csv; average them over datasets
    means = b.groupby("arm")[["accuracy", "macro_f1"]].mean()
    rows = "\n".join(f"{LABEL[arm]} & {means.accuracy[arm]:.2f} & "
                     f"{means.macro_f1[arm]:.2f} \\\\" for arm in ROWS)
    write("table_results.tex", header +
          "\\begin{tabular}{lrr}\n\\toprule\nMethod & Accuracy & Macro-F1 \\\\\n"
          "\\midrule\n" + rows + "\n\\bottomrule\n\\end{tabular}\n")

    # per-dataset accuracy for all ten arms (the two reference arms included)
    acc = b.pivot_table(index="dataset", columns="arm", values="accuracy")
    head = " & ".join(LABEL[arm].replace("\\ ", "~") for arm in ALL_ARMS)
    body = "\n".join(f"{ds} & " + " & ".join(f"{acc[arm][ds]:.2f}" for arm in ALL_ARMS)
                     + " \\\\" for ds in sorted(acc.index))
    write("table_results_datasets.tex", header +
          "\\begin{tabular}{l" + "r" * len(ALL_ARMS) + "}\n\\toprule\n"
          "Dataset & " + head + " \\\\\n\\midrule\n" + body +
          "\n\\bottomrule\n\\end{tabular}\n")

    # protocol A vs B: the manuscript reports protocol A's accuracy only
    a = metrics[metrics.protocol == "A before-CV"].set_index(["arm", "dataset"])
    bidx = b.set_index(["arm", "dataset"])
    arms = [arm for arm in ALL_ARMS if arm in a.index.get_level_values(0)]
    rows = "\n".join(
        f"{LABEL[arm]} & {bidx.accuracy.loc[arm].mean():.2f} & "
        f"{a.accuracy.loc[arm].mean():.2f} & "
        f"{a.accuracy.loc[arm].mean() - bidx.accuracy.loc[arm].mean():+.2f} \\\\"
        for arm in arms)
    write("table_results_A.tex", header +
          "\\begin{tabular}{lrrr}\n\\toprule\n"
          "Method & Fold-specific & Before CV & Difference \\\\\n\\midrule\n"
          + rows + "\n\\bottomrule\n\\end{tabular}\n")


if __name__ == "__main__":
    main()
